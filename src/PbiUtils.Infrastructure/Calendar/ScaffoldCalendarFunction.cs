using System.Text.Json;
using PbiUtils.Application.Scaffolding;
using PbiUtils.Core;
using TOM = Microsoft.AnalysisServices.Tabular;

using PbiUtils.Infrastructure.Models.Configuration;

using PbiUtils.Application.Calendar;
using PbiUtils.Application.Models.Configuration;

namespace PbiUtils.Infrastructure.Calendar;

internal static partial class ScaffoldCalendarWriter
{
    private const string FunctionAnnotation = "PbiUtils.Configuration.CalendarFunction.v1";
    private sealed record FunctionOwner(int SchemaVersion, string TableName, string GeneratorVersion, string Locale);

    /// <summary>只有表和函数全部事实仍有效才返回已记录绑定.</summary>
    internal static ModelConfigurationCalendarFunction? FunctionBinding(TOM.Table table) =>
        table.Annotations.Find(OptionsAnnotation) is null ? null : ReadDocument(table).Function;

    /// <summary>表归属不覆盖独立函数; 必须同时核验代码、调用、Kind及唯一绑定.</summary>
    private static void VerifyFunction(TOM.Table table, CalendarDocument document)
    {
        var binding = document.Function;
        var function = binding is null ? null : table.Model?.Expressions.Find(binding.FunctionName);
        if (binding is null || binding.FunctionName != ScaffoldCalendarM.FunctionName || function is null || function.Name != binding.FunctionName || function.Kind != TOM.ExpressionKind.M
            || binding.GeneratorVersion != document.GeneratorVersion
            || binding.GeneratorVersion != ScaffoldCalendarM.FunctionGeneratorVersion
            || binding.ResourceVersion != ScaffoldCalendar.LunarResourceVersion
            || function.QueryGroup?.Name != "functions"
            || binding.Locale is not ("zh-cn" or "en-us") || function.Annotations.Find("PBI_ResultType")?.Value != "Function"
            || function.Annotations.Find(FunctionAnnotation)?.Value != JsonSerializer.Serialize(new FunctionOwner(1, table.Name, binding.GeneratorVersion, binding.Locale))
            || table.Partitions.Count != 1 || table.Partitions[0].Mode != TOM.ModeType.Import || table.Partitions[0].Source is not TOM.MPartitionSource source
            || CalendarProgramPlanner.CodeHash(function.Expression) != binding.DefinitionHash || CalendarProgramPlanner.CodeHash(source.Expression) != binding.InvocationHash)
            throw FunctionConflict();
        ModelConfigurationOwnership.Require(function, function.Annotations);
        CalendarProgramPlanner.RequireName(table.Model!, binding.FunctionName, table, binding);
    }

    /// <summary>在调用方拥有的同一候选模型内写函数; 已有绑定必须在更改表之前核验.</summary>
    private static void WriteFunction(TOM.Table table, ScaffoldCalendarProgram program, ModelConfigurationCalendarFunction? binding)
    {
        var model = table.Model ?? throw FunctionConflict();
        CalendarProgramPlanner.RequireName(model, program.FunctionName, table, binding);
        var function = model.Expressions.Find(program.FunctionName);
        if (function is null)
        {
            function = new TOM.NamedExpression { Name = program.FunctionName, Kind = TOM.ExpressionKind.M };
            model.Expressions.Add(function);
        }
        function.Expression = program.FunctionExpression;
        function.Description = program.Locale == "en-us" ? "Calendar function generated by pbi-utils." : "pbi-utils 生成的日期函数.";
        var group = model.QueryGroups.Find("functions");
        if (group is null)
        {
            group = new TOM.QueryGroup { Folder = "functions" };
            model.QueryGroups.Add(group);
        }
        function.QueryGroup = group;
        static void Set(TOM.NamedExpression item, string name, string value)
        {
            if (item.Annotations.Find(name) is { } prior) item.Annotations.Remove(prior);
            item.Annotations.Add(new TOM.Annotation { Name = name, Value = value });
        }
        Set(function, "PBI_ResultType", "Function");
        Set(function, FunctionAnnotation, JsonSerializer.Serialize(new FunctionOwner(1, table.Name, program.GeneratorVersion, program.Locale)));
        ModelConfigurationOwnership.Mark(function, function.Annotations);
    }

    private static AppException FunctionConflict() => new("CONFIGURATION_CALENDAR_FUNCTION_CONFLICT", "日期函数缺失、已改变或绑定无效, 未覆盖", 3);
}
