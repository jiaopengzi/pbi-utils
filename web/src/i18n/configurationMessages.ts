/** 为两种语言添加共同命名空间, 不缓存翻译后的运行时标签. */
function namespace(values: Record<string, string>): Record<string, string> {
    return Object.fromEntries(Object.entries(values).map(([key, value]) => [`configuration.${key}`, value]))
}
export const configurationMessages = { "zh-cn": namespace(zh), "en-us": namespace(en) }
